/**
 * ziha-bookmarks.html → bookmarks-seed.sql
 *
 * 사용법:
 *   node scripts/import-bookmarks.mjs [파일경로]
 *
 * 기본 입력: src/assets/ziha-bookmarks.html
 * 출력:      scripts/bookmarks-seed.sql
 *
 * 생성 후 D1에 적용하려면:
 *   npx wrangler d1 execute bl-house --local  --file=scripts/bookmarks-seed.sql
 *   npx wrangler d1 execute bl-house --remote --file=scripts/bookmarks-seed.sql
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const inputPath = process.argv[2]
  ?? path.join(__dirname, '../src/assets/ziha-bookmarks.html');
const outputPath = path.join(__dirname, 'bookmarks-seed.sql');

const html = fs.readFileSync(inputPath, 'utf-8');

// <A HREF="url" ...>title</A> 패턴 추출
const re = /<A\s+HREF="([^"]+)"[^>]*>([^<]+)<\/A>/gi;
const rows = [];
let m;
while ((m = re.exec(html)) !== null) {
  const url   = m[1].trim();
  const title = m[2].trim().replace(/'/g, "''"); // SQL escape
  const cleanUrl = url.replace(/'/g, "''");
  rows.push(`('${title}', '${cleanUrl}', 0)`);
}

const sql = [
  '-- auto-generated by scripts/import-bookmarks.mjs',
  `-- source: ${path.basename(inputPath)}`,
  `-- rows: ${rows.length}`,
  '',
  'INSERT INTO bookmarks (title, url, star) VALUES',
  rows.map((r, i) => `  ${r}${i < rows.length - 1 ? ',' : ';'}`).join('\n'),
].join('\n');

fs.writeFileSync(outputPath, sql, 'utf-8');
console.log(`✓ ${rows.length}개 북마크 → ${outputPath}`);
